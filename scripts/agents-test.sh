#!/usr/bin/env sh
# Regression tests for `scripts/agents.sh check`: mutate a skill in a scratch copy and assert the
# checker accepts or rejects it. Run from anywhere; touches nothing in the working tree.
set -u
root="$(cd "$(dirname "$0")/.." && pwd)"
failures=0

new_copy() {
  tmp="$(mktemp -d)"
  mkdir -p "$tmp/scripts" "$tmp/.claude"
  cp -R "$root/.agents" "$tmp/.agents"
  cp -R "$root/.claude/skills" "$tmp/.claude/skills"
  cp "$root/scripts/agents.sh" "$tmp/scripts/agents.sh"
}

# expect <pass|fail> <description> <mutation: sh snippet run in the copy, applied to both trees>
expect() {
  want="$1"; label="$2"; mutate="$3"
  new_copy
  ( cd "$tmp" && for tree in .agents/skills .claude/skills; do
      f="$tree/add-guard/SKILL.md"; eval "$mutate"
    done )
  if ( cd "$tmp" && sh scripts/agents.sh check >/dev/null 2>&1 ); then got=pass; else got=fail; fi
  if [ "$got" = "$want" ]; then echo "ok   $label"; else echo "FAIL $label (expected $want, got $got)"; failures=$((failures + 1)); fi
  rm -rf "$tmp"
}

expect pass "untouched tree"                      ':'
expect fail "missing closing ---"                 'awk "BEGIN{n=0} /^---\$/{n++; if(n==2) next} {print}" "$f" > "$f.new" && mv "$f.new" "$f"'
expect fail "no opening ---"                      'sed 1d "$f" > "$f.new" && mv "$f.new" "$f"'
expect fail "wrong name"                          'sed "s/^name: add-guard/name: other/" "$f" > "$f.new" && mv "$f.new" "$f"'
expect fail "empty description"                   'sed "s/^description:.*/description:/" "$f" > "$f.new" && mv "$f.new" "$f"'
expect fail "missing description"                 'sed "/^description:/d" "$f" > "$f.new" && mv "$f.new" "$f"'
expect pass "CRLF line endings (Windows checkout)" 'sed "s/\$/\\r/" "$f" > "$f.new" && mv "$f.new" "$f"'
expect pass "description starting with t or backslash" 'sed "s/^description:.*/description: terse \\\\ text/" "$f" > "$f.new" && mv "$f.new" "$f"'

# drift between the two trees must still fail
new_copy
echo "extra" >> "$tmp/.claude/skills/add-guard/SKILL.md"
if ( cd "$tmp" && sh scripts/agents.sh check >/dev/null 2>&1 ); then echo "FAIL drift not detected"; failures=$((failures + 1)); else echo "ok   drift between trees"; fi
rm -rf "$tmp"

# ---- pre-commit hook: it must judge the staged blobs, not the working tree ----
hook_case() {  # <expect pass|fail> <label> <staging snippet>
  want="$1"; label="$2"; stage="$3"
  new_copy
  mkdir -p "$tmp/scripts/git-hooks"
  cp "$root/scripts/git-hooks/pre-commit" "$tmp/scripts/git-hooks/pre-commit"
  (
    cd "$tmp"
    git init -q
    git add -A
    git -c user.name=t -c user.email=t@example.invalid -c commit.gpgsign=false commit -q -m base
    # edit the skill in BOTH trees so the working tree is consistent, then stage only some of it
    for tree in .agents/skills .claude/skills; do echo "edited" >> "$tree/add-guard/SKILL.md"; done
    eval "$stage"
  )
  if ( cd "$tmp" && sh scripts/git-hooks/pre-commit >/dev/null 2>&1 ); then got=pass; else got=fail; fi
  if [ "$got" = "$want" ]; then echo "ok   hook: $label"; else echo "FAIL hook: $label (expected $want, got $got)"; failures=$((failures + 1)); fi
  rm -rf "$tmp"
}

hook_case fail "only .agents/skills staged, working copies match" 'git add .agents/skills'
hook_case fail "only .claude/skills staged"                         'git add .claude/skills'
hook_case pass "both copies staged"                                 'git add .agents/skills .claude/skills'
hook_case pass "no skill files staged"                              'echo x > notes.txt; git add notes.txt'

# ---- commit-msg hook ----
msg_case() {  # <expect pass|fail> <message>
  want="$1"; message="$2"
  file="$(mktemp)"; printf '%s\n' "$message" > "$file"
  if sh "$root/scripts/git-hooks/commit-msg" "$file" >/dev/null 2>&1; then got=pass; else got=fail; fi
  rm -f "$file"
  if [ "$got" = "$want" ]; then echo "ok   commit-msg: $message"; else echo "FAIL commit-msg: $message (expected $want, got $got)"; failures=$((failures + 1)); fi
}
msg_case pass "fix: handle empty input"
msg_case pass "chore: regenerate bindings (Generated with protoc from api.proto)"
msg_case pass "docs: explain how the code is generated by the build script"
msg_case fail "feat: x

Co-Authored-By: Someone <a@b.example>"
msg_case fail "feat: x

co-authored-by: Claude <noreply@anthropic.com>"
msg_case fail "feat: x

Generated with [Claude Code](https://claude.com/claude-code)"
msg_case fail "feat: x

Generated with [Codex]"
msg_case fail "feat: x

Generated with Cursor"
msg_case fail "feat: x

Generated by Copilot"
msg_case fail "feat: x

🤖 Generated with Claude Code"

[ "$failures" -eq 0 ] && echo "all checker tests passed" || { echo "$failures checker test(s) failed"; exit 1; }
